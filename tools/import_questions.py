#!/usr/bin/env python3
"""Build questions.js for AIR Ladder from the JEEBench dataset (IIT Delhi DAIR group, MIT licence).

    python3 tools/import_questions.py                 # downloads data.zip from GitHub
    python3 tools/import_questions.py path/to/data.zip
    python3 tools/import_questions.py --out my_questions.js

Only single-correct MCQs are kept, because the app shows four options and one right answer.
Numeric, integer and multiple-correct problems are skipped.

Licence note: JEEBench is MIT-licensed by its authors, but the problems come from JEE Advanced
papers set by the IITs. Check you are allowed to republish them before you put them on a public
or paid site. Every imported question keeps a source line so you can credit it.
"""
import argparse
import io
import json
import re
import sys
import urllib.request
import zipfile

URL = "https://github.com/dair-iitd/jeebench/raw/main/data.zip"
SUBJECTS = {"phy": "Physics", "chem": "Chemistry", "math": "Maths"}
SPLIT = re.compile(r"\n\s*[(\[]([A-D])[)\]]\s*")  # options written (A) or [A]


def read_dataset(path):
    if path:
        raw = open(path, "rb").read()
    else:
        print("Downloading", URL, file=sys.stderr)
        raw = urllib.request.urlopen(URL, timeout=120).read()
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        name = next(n for n in z.namelist() if n.endswith("dataset.json"))
        return json.loads(z.read(name).decode("utf-8"))


def convert(records):
    out, skipped, counters = [], {"not single MCQ": 0, "options not parseable (other format)": 0}, {}
    for pos, r in enumerate(records):
        if r.get("type") != "MCQ":
            skipped["not single MCQ"] += 1
            continue
        parts = SPLIT.split(r["question"])
        # parts = [statement, 'A', textA, 'B', textB, 'C', textC, 'D', textD]
        letters = parts[1::2]
        if letters != ["A", "B", "C", "D"] or r.get("gold") not in letters:
            skipped["options not parseable (other format)"] += 1
            continue
        subject = SUBJECTS[r["subject"]]
        key = (r["description"], subject)
        counters[key] = counters.get(key, 0) + 1
        out.append({
            "id": "jb%03d" % pos,  # "index" in the dataset restarts for every paper, so use the position
            "t": "%s, %s #%d" % (r["description"], subject, counters[key]),
            "d": "H",  # the dataset has no difficulty label; JEE Advanced is treated as Hard
            "s": subject,
            "x": ["jee"],
            "tp": "JEE Advanced previous year",
            "q": parts[0].strip(),
            "o": [t.strip() for t in parts[2::2]],
            "a": letters.index(r["gold"]),
            "e": "",
            "m": 150,
            "src": "JEEBench (IIT Delhi DAIR, MIT licence), %s" % r["description"],
        })
    return out, skipped


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("zip", nargs="?", help="path to a local data.zip (optional)")
    ap.add_argument("--out", default="questions.js")
    args = ap.parse_args()
    questions, skipped = convert(read_dataset(args.zip))
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("/* Generated by import_questions.py */\nwindow.EXTRA_QUESTIONS = ")
        json.dump(questions, f, ensure_ascii=False)
        f.write(";\n")
    by = {}
    for q in questions:
        by[q["s"]] = by.get(q["s"], 0) + 1
    print("Wrote %d questions to %s %s" % (len(questions), args.out, by))
    print("Skipped:", skipped)


if __name__ == "__main__":
    main()